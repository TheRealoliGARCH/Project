"""Generate LaTeX empirical-result content from reproducible pipeline outputs."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUTPUT = ROOT / "paper" / "generated_empirical_results.tex"


def read_rows(name):
    with (RESULTS / name).open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def esc(value):
    return str(value).replace("_", "\\_")


def main():
    parameters = read_rows("nss_parameters_2025-06.csv")
    discounts = read_rows("discount_factors_2025-06.csv")
    lines = [
        "\\section{Reproducible June 2025 Greece--Italy Results}",
        "This section is generated automatically by the repository workflow from the empirical output files. The underlying inputs are benchmark yields transformed according to the repository's declared modeling convention; the resulting curves are therefore NSS model-implied discount factors rather than directly observed zero-coupon discount factors.",
        "",
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{NSS estimation diagnostics generated by the empirical pipeline.}",
        "\\begin{tabular}{lrrrrrrr}",
        "\\toprule",
        "Country & $\\beta_0$ & $\\beta_1$ & $\\beta_2$ & $\\beta_3$ & $\\tau_1$ & $\\tau_2$ & RMSE\\\\",
        "\\midrule",
    ]
    for row in parameters:
        lines.append(
            f"{esc(row['country'])} & {float(row['beta0']):.8f} & {float(row['beta1']):.8f} & "
            f"{float(row['beta2']):.8f} & {float(row['beta3']):.8f} & {float(row['tau1']):.4f} & "
            f"{float(row['tau2']):.4f} & {float(row['rmse']):.8f}\\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\begin{table}[ht]",
        "\\centering",
        "\\caption{NSS model-implied Greece--Italy discount-factor comparison.}",
        "\\begin{tabular}{rrrr}",
        "\\toprule",
        "Maturity & Greece & Italy & $\\Delta D= D_{\\mathrm{GR}}-D_{\\mathrm{IT}}$\\\\",
        "\\midrule",
    ]
    for row in discounts:
        lines.append(
            f"{float(row['maturity_years']):.1f} & {float(row['greece_discount_factor']):.8f} & "
            f"{float(row['italy_discount_factor']):.8f} & {float(row['difference_gr_minus_it']):.8f}\\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        "",
        "\\begin{figure}[ht]",
        "\\centering",
        "\\includegraphics[width=0.9\\textwidth]{generated/greece_italy_discount_factors_2025-06.png}",
        "\\caption{Automatically generated NSS model-implied discount-factor comparison.}",
        "\\end{figure}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
